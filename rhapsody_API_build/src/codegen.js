'use strict';

// Code generation: patches the headers of the working copy and produces api_gen.cpp.

const TRACK_INCLUDE = '#include "rhapsody_api_track.h"';
const PATCH_MARK = 'RHAPSODY_API_PATCH';

function cstr(s) {
  return JSON.stringify(String(s));
}

function eol(text) {
  return text.includes('\r\n') ? '\r\n' : '\n';
}

// Adds the tracker member (and the friend access struct) to every exposed class of one header.
// `classes` are the parsed classes of this header (with markerIndex / closeIndex). Edits go from the end to the start.
function patchHeader(text, classes) {
  if (text.includes(PATCH_MARK)) return text;
  const nl = eol(text);
  const edits = [];
  for (const c of classes) {
    const reactivePtr = c.reactive ? 'static_cast<void*>(static_cast<OMReactive*>(this))' : 'nullptr';
    const insert =
      `  /* ${PATCH_MARK} */${nl}` +
      `  friend struct RhapsodyApiAccess;${nl}` +
      `private:${nl}` +
      `  ::RhapsodyApi::Tracker _rhapi_tracker{${cstr(c.name)}, static_cast<void*>(this), ${reactivePtr}};${nl}`;
    edits.push({ at: c.closeIndex, text: insert });
    edits.push({ at: c.markerIndex, text: `${TRACK_INCLUDE}${nl}` });
  }
  edits.sort((a, b) => b.at - a.at);
  let out = text;
  for (const e of edits) out = out.slice(0, e.at) + e.text + out.slice(e.at);
  return out;
}

function arrayLiteral(items) {
  return items.length ? `{ ${items.join(', ')} }` : '';
}

function generateApiCpp({ filtered, schemaText, config, headers }) {
  const L = [];
  const push = (s = '') => L.push(s);
  push('// Generated by rhapsody-api-build. Do not edit.');
  push('#include <cstddef>');
  for (const h of headers) push(`#include "${h}"`);
  push('#include "rhapsody_api_desc.h"');
  push('#include "rhapsody_api_convert.h"');
  push('');
  push('struct RhapsodyApiAccess {');

  const classIdx = new Map();
  filtered.classes.forEach((c, ci) => {
    classIdx.set(c.name, ci);
    c.attributes.forEach((a, ai) => {
      push(`  static ::RhapsodyApi::Json g${ci}_${ai}(void* o) { return ::RhapsodyApi::toJson(static_cast<${c.name}*>(o)->${a.name}); }`);
      if (a.writable) {
        push(
          `  static bool s${ci}_${ai}(void* o, const ::RhapsodyApi::Json& v, int i, std::string& e) { return ::RhapsodyApi::setValue(static_cast<${c.name}*>(o)->${a.name}, v, i, e); }`
        );
      }
    });
  });

  filtered.events.forEach((ev, ei) => {
    push(`  static bool ev${ei}(void* r, const ::RhapsodyApi::Json& a, std::string& e) {`);
    ev.args.forEach((arg, k) => {
      push(`    ${arg.cppType} p${k} = ${arg.cppType}();`);
      push(`    if (!::RhapsodyApi::argFromJson(a, ${k}, ${cstr(arg.name)}, p${k}, e)) return false;`);
    });
    if (!ev.args.length) push('    (void)a; (void)e;');
    push(`    static_cast<OMReactive*>(r)->GEN(${ev.name}(${ev.args.map((_, k) => `p${k}`).join(', ')}));`);
    push('    return true;');
    push('  }');
  });
  push('};');
  push('');
  push('namespace RhapsodyApi {');
  push('namespace {');

  filtered.classes.forEach((c, ci) => {
    if (!c.attributes.length) return;
    push(`const AttrDesc attrs${ci}[] = {`);
    c.attributes.forEach((a, ai) => {
      push(`  { ${cstr(a.name)}, ${a.writable ? 'true' : 'false'}, &RhapsodyApiAccess::g${ci}_${ai}, ${a.writable ? `&RhapsodyApiAccess::s${ci}_${ai}` : 'nullptr'} },`);
    });
    push('};');
  });

  const classRows = filtered.classes.map((c, ci) =>
    c.attributes.length ? `  { ${cstr(c.name)}, attrs${ci}, ${c.attributes.length} },` : `  { ${cstr(c.name)}, nullptr, 0 },`
  );
  push(`const ClassDesc classes[] = {${classRows.length ? '' : ' { nullptr, nullptr, 0 }'}`);
  classRows.forEach((r) => push(r));
  push('};');

  filtered.events.forEach((ev, ei) => {
    if (ev.args.length) push(`const char* const evArgs${ei}[] = ${arrayLiteral(ev.args.map((a) => cstr(a.name)))};`);
    if (ev.handledBy.length) push(`const char* const evHandled${ei}[] = ${arrayLiteral(ev.handledBy.map(cstr))};`);
  });
  const eventRows = filtered.events.map((ev, ei) =>
    `  { ${cstr(ev.name)}, ${ev.args.length}, ${ev.args.length ? `evArgs${ei}` : 'nullptr'}, ${ev.handledBy.length ? `evHandled${ei}` : 'nullptr'}, ${ev.handledBy.length}, &RhapsodyApiAccess::ev${ei} },`
  );
  push(`const EventDesc events[] = {${eventRows.length ? '' : ' { nullptr, 0, nullptr, nullptr, 0, nullptr }'}`);
  eventRows.forEach((r) => push(r));
  push('};');

  // A byte array avoids the MSVC string literal size limit.
  const bytes = Buffer.from(schemaText, 'utf8');
  push(`const char schemaBytes[] = {`);
  for (let i = 0; i < bytes.length; i += 24) push('  ' + Array.from(bytes.subarray(i, i + 24)).join(',') + ',');
  push('  0');
  push('};');

  push(`const GeneratedApi api = {`);
  push(`  classes, ${filtered.classes.length}, events, ${filtered.events.length},`);
  push(`  schemaBytes, ${bytes.length},`);
  push(`  ${cstr(config.server.host)}, ${config.server.port}, ${config.server.pushRateHz}, ${cstr(config.web.dir)}, ${cstr(config.web.route)}, ${cstr(config.customWeb.dir)}, ${cstr(config.customWeb.route)}, ${cstr(config.server.token || '')}, ${config.server.cors ? 'true' : 'false'}`);
  push('};');
  push('} // namespace');
  push('');
  push('const GeneratedApi& generatedApi() { return api; }');
  push('} // namespace RhapsodyApi');
  push('');
  return L.join('\n');
}

module.exports = { patchHeader, generateApiCpp, PATCH_MARK };
