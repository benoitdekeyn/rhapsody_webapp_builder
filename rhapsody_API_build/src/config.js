const fs = require('fs');
const path = require('path');
const { parseJsonc } = require('./jsonc');

const CONFIG_NAME = 'rhapsody-api.config.jsonc';

const DEFAULTS = {
  codeDir: '',
  exe: './dist/simulateur.exe',
  schema: {
    dir: '',            // default: "schemas" next to the executable
    baseName: 'api_schema',
  },
  server: {
    host: '127.0.0.1',
    port: 8080,
    pushRateHz: 20,
    cors: true,
    token: '',
  },
  web: {
    source: './api_web_interface', // simple API explorer page, copied next to the executable ("" to disable)
    dir: 'api_web_interface',      // folder name next to the executable
    route: '/api',                 // URL prefix where it is served
  },
  customWeb: {
    source: './custom_web_interface', // user website (html, css, js, media...), "" to disable
    dir: 'custom_web_interface',      // folder name next to the executable
    route: '/custom',                 // URL prefix where it is served
    siteConfig: 'site.json',          // file inside source: { "api": { "host", "port", "token" } }, never copied
  },
  copyTo: [],           // extra folders receiving a full copy of the executable folder
  exclude: {
    classes: [],
    attributes: [],
    events: [],
  },
  readOnly: [],
  typeMap: {},
  assets: [],
  build: {
    workDir: './build/work',
    buildType: 'Debug',
    instrumentation: 'None',
    extraDefines: [],
    extraIncludes: [],
    extraLibs: [],
    extraCompilerFlags: [],
    extraLinkerFlags: [],
    excludeSources: [],
    vcvarsPath: '',
    rhapsodyRoot: '',
    frameworkLibRoot: '',
    libPrefix: '',
    keepWorkDir: true,
    smokeTest: true,
    smokeTestTimeoutSec: 20,
  },
  run: {
    cwd: '',
    args: [],
  },
};

function isPlainObject(v) {
  return v && typeof v === 'object' && !Array.isArray(v);
}

function merge(base, extra, trail = '') {
  const out = Array.isArray(base) ? [...base] : { ...base };
  for (const [key, value] of Object.entries(extra || {})) {
    const where = trail ? `${trail}.${key}` : key;
    if (!(key in base)) throw new Error(`Unknown configuration key "${where}"`);
    if (isPlainObject(base[key]) && Object.keys(base[key]).length && isPlainObject(value)) {
      out[key] = merge(base[key], value, where);
    } else if (typeof base[key] !== 'undefined' && base[key] !== null && typeof value !== typeof base[key] && !(Array.isArray(base[key]) && Array.isArray(value))) {
      throw new Error(`Configuration key "${where}" must be of type ${Array.isArray(base[key]) ? 'array' : typeof base[key]}`);
    } else {
      out[key] = value;
    }
  }
  return out;
}

function findConfig(startDir) {
  const candidate = path.join(startDir, CONFIG_NAME);
  return fs.existsSync(candidate) ? candidate : null;
}

// Loads the JSONC file and resolves every path relative to the config file location.
function loadConfig(configPath, overrides = {}) {
  const file = path.resolve(configPath);
  if (!fs.existsSync(file)) throw new Error(`Configuration file not found: ${file}`);
  const raw = parseJsonc(fs.readFileSync(file, 'utf8'), path.basename(file));
  for (const [dotted, value] of Object.entries(overrides.set || {})) {
    const keys = dotted.split('.');
    let node = raw;
    for (const k of keys.slice(0, -1)) node = isPlainObject(node[k]) ? node[k] : (node[k] = {});
    node[keys[keys.length - 1]] = value;
  }
  const cfg = merge(structuredClone(DEFAULTS), raw);
  if (typeof overrides.smokeTest === 'boolean') cfg.build.smokeTest = overrides.smokeTest;
  if (typeof overrides.keepWork === 'boolean') cfg.build.keepWorkDir = overrides.keepWork;

  const root = path.dirname(file);
  const abs = (p) => (p ? path.resolve(root, p) : '');

  if (!cfg.codeDir) throw new Error('"codeDir" is required (folder generated by Rhapsody, e.g. ".../CodesGeneres/ModeAnimation")');
  cfg.configFile = file;
  cfg.root = root;
  cfg.codeDir = abs(cfg.codeDir);
  cfg.exe = abs(cfg.exe);
  if (!/\.exe$/i.test(cfg.exe)) throw new Error('"exe" must end with .exe');
  cfg.schema.dir = cfg.schema.dir ? abs(cfg.schema.dir) : path.join(path.dirname(cfg.exe), 'schemas');
  cfg.web.source = abs(cfg.web.source);
  cfg.customWeb.source = abs(cfg.customWeb.source);
  cfg.copyTo = [...cfg.copyTo.map(abs), ...(overrides.copyTo || []).map((p) => path.resolve(p))];
  cfg.site = null;
  const siteFile = cfg.customWeb.source && cfg.customWeb.siteConfig ? path.join(cfg.customWeb.source, cfg.customWeb.siteConfig) : '';
  if (siteFile && fs.existsSync(siteFile)) {
    const site = parseJsonc(fs.readFileSync(siteFile, 'utf8'), siteFile);
    const a = site.api || {};
    if (a.port !== undefined && (!Number.isInteger(a.port) || a.port < 0 || a.port > 65535)) throw new Error(`${siteFile}: "api.port" must be an integer between 0 and 65535`);
    if (a.host !== undefined && (typeof a.host !== 'string' || !a.host)) throw new Error(`${siteFile}: "api.host" must be a non-empty string`);
    if (a.token !== undefined && typeof a.token !== 'string') throw new Error(`${siteFile}: "api.token" must be a string`);
    cfg.site = { file: siteFile, host: a.host, port: a.port, token: a.token };
    // The API served by the executable must be the one the website reads.
    if (a.host) cfg.server.host = a.host.toLowerCase() === 'localhost' ? '127.0.0.1' : a.host;
    if (a.port !== undefined) cfg.server.port = a.port;
    if (a.token !== undefined) cfg.server.token = a.token;
  }
  if (typeof overrides.port === 'number') cfg.server.port = overrides.port;
  if (overrides.host) cfg.server.host = overrides.host;
  for (const [name, m] of [['web', cfg.web], ['customWeb', cfg.customWeb]]) {
    if (!/^\/[\w.-]*(\/[\w.-]+)*$/.test(m.route) || m.route.length > 1 && m.route.endsWith('/')) throw new Error(`"${name}.route" must look like "/custom" (no trailing slash)`);
    if (!/^[\w.-]+$/.test(m.dir)) throw new Error(`"${name}.dir" may only contain letters, digits, "_", "-" and "."`);
  }
  if (cfg.web.route === cfg.customWeb.route) throw new Error('"web.route" and "customWeb.route" must be different');
  if (cfg.web.dir === cfg.customWeb.dir) throw new Error('"web.dir" and "customWeb.dir" must be different');
  cfg.build.workDir = abs(cfg.build.workDir);
  cfg.run.cwd = cfg.run.cwd ? abs(cfg.run.cwd) : path.dirname(cfg.exe);
  cfg.assets = cfg.assets.map((a) => {
    if (!isPlainObject(a) || !a.from || !a.to) throw new Error('"assets" entries must look like { "from": "...", "to": "..." } (to is relative to the executable folder)');
    return { from: abs(a.from), to: a.to };
  });

  if (!Number.isInteger(cfg.server.port) || cfg.server.port < 0 || cfg.server.port > 65535) throw new Error('"server.port" must be an integer between 0 and 65535 (0 disables the server)');
  if (!Number.isInteger(cfg.server.pushRateHz) || cfg.server.pushRateHz < 1 || cfg.server.pushRateHz > 1000) throw new Error('"server.pushRateHz" must be an integer between 1 and 1000');
  if (!/^[\w.-]+$/.test(cfg.schema.baseName)) throw new Error('"schema.baseName" may only contain letters, digits, "_", "-" and "."');
  if (!['Debug', 'Release'].includes(cfg.build.buildType)) throw new Error('"build.buildType" must be "Debug" or "Release"');
  if (!['None', 'Animation'].includes(cfg.build.instrumentation)) throw new Error('"build.instrumentation" must be "None" or "Animation"');
  if (!fs.existsSync(cfg.codeDir)) throw new Error(`"codeDir" does not exist: ${cfg.codeDir}`);
  return cfg;
}

module.exports = { loadConfig, findConfig, CONFIG_NAME, DEFAULTS };
